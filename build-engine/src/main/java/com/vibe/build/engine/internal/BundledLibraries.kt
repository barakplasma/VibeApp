package com.vibe.build.engine.internal

import android.util.Log
import com.tyron.builder.BuildModule
import java.io.File

/**
 * One library VibeApp bundles for the apps it generates.
 *
 * Bundled libraries ship as assets inside VibeApp and are extracted to `filesDir` on
 * first use. Every entry here is always-on: it lands on the javac classpath and in every
 * generated APK. Adding a library should be a row in [BundledLibraries.ALL] plus the
 * matching assets, not a new field threaded through the pipeline.
 *
 * @param id stable short name, used in logs
 * @param classesAsset asset holding the library's classes. A `.zip` is unzipped; anything
 *   else is copied verbatim. The extracted file name is the asset name minus `.zip`.
 * @param resCompiledAsset optional asset holding AAPT2-precompiled `.flat` resources,
 *   expanded into a directory and passed to `aapt2 link` as `-R` overlays.
 * @param extraPackages packages needing an R class generated by `aapt2 link`
 *   (`--extra-packages`), so library code can resolve its own `R` references.
 * @param stripRClasses whether to drop `R`/`R$*` classes before dexing. AAPT2 regenerates
 *   the authoritative R classes per build; stale ones from the library's original build
 *   would shadow them and misresolve resource IDs.
 * @param optional when true, a missing asset is expected rather than logged as a problem.
 *   This is how a build flavor opts out of a library.
 */
data class BundledLibrary(
    val id: String,
    val classesAsset: String,
    val resCompiledAsset: String? = null,
    val extraPackages: List<String> = emptyList(),
    val stripRClasses: Boolean = true,
    val optional: Boolean = false,
) {
    /** File name under `filesDir` the classes asset extracts to. */
    val extractedName: String get() = classesAsset.removeSuffix(".zip")

    /** Directory name under `filesDir` the compiled resources expand into. */
    val resCompiledDirName: String? get() = resCompiledAsset?.removeSuffix(".zip")
}

/** A [BundledLibrary] whose assets were found on disk. */
data class ResolvedLibrary(
    val spec: BundledLibrary,
    val jar: File,
    val resCompiledDir: File? = null,
) {
    val id: String get() = spec.id
    val extraPackages: List<String> get() = spec.extraPackages
    val stripRClasses: Boolean get() = spec.stripRClasses
}

object BundledLibraries {

    private const val TAG = "BundledLibraries"

    /**
     * Order matters: these reach the javac classpath and D8 in this order, so an earlier
     * entry wins when two libraries carry the same class.
     */
    val ALL: List<BundledLibrary> = listOf(
        BundledLibrary(
            id = "androidx",
            classesAsset = "androidx-classes.jar.zip",
            resCompiledAsset = "androidx-res-compiled.zip",
            extraPackages = listOf(
                "androidx.appcompat",
                "androidx.appcompat.resources",
                "androidx.cardview",
                "androidx.constraintlayout.widget",
                "androidx.coordinatorlayout",
                "androidx.core",
                "androidx.fragment",
                "androidx.lifecycle.runtime",
                "androidx.lifecycle.viewmodel",
                "androidx.recyclerview",
                "androidx.savedstate",
                "androidx.transition",
                "androidx.viewpager2",
                "com.google.android.material",
            ),
        ),
        // Generated apps extend ShadowActivity, which delegates to Activity in
        // standalone mode. Shipped as a raw jar rather than a zip.
        BundledLibrary(
            id = "shadow-runtime",
            classesAsset = "shadow-runtime.jar",
        ),
        BundledLibrary(
            id = "jsoup",
            classesAsset = "jsoup.jar.zip",
        ),
        // Retrofit + Moshi (+ OkHttp, Okio) for typesafe HTTP and JSON mapping.
        BundledLibrary(
            id = "retrofit",
            classesAsset = "retrofit.jar.zip",
        ),
        // AndroidX ExifInterface: image orientation, needed to display or process
        // photos the right way up. Ships no resources, so no overlay asset.
        BundledLibrary(
            id = "exifinterface",
            classesAsset = "exifinterface.jar.zip",
        ),
        // Preference (settings screens) and Biometric (fingerprint/face unlock). Both
        // ship resources, so they need the overlay asset and an R class per package.
        BundledLibrary(
            id = "jetpack-ui",
            classesAsset = "jetpack-ui.jar.zip",
            resCompiledAsset = "jetpack-ui-res-compiled.zip",
            extraPackages = listOf("androidx.preference", "androidx.biometric"),
        ),
    )

    /**
     * Extracts every catalog entry whose assets are present and returns them in [ALL]
     * order. Entries with missing assets are skipped, so a flavor that ships fewer
     * assets simply gets fewer libraries.
     */
    fun resolve(): List<ResolvedLibrary> = ALL.mapNotNull { spec ->
        val jar = BuildModule.getBundledFile(spec.classesAsset, spec.extractedName)
            ?.takeIf { it.exists() }
        if (jar == null) {
            if (!spec.optional) {
                Log.w(TAG, "Bundled library '${spec.id}' is missing asset ${spec.classesAsset}")
            }
            return@mapNotNull null
        }
        val resCompiledDir = spec.resCompiledAsset?.let { asset ->
            BuildModule.getBundledDir(asset, spec.resCompiledDirName!!)
                ?.takeIf { it.exists() && it.isDirectory }
        }
        ResolvedLibrary(spec = spec, jar = jar, resCompiledDir = resCompiledDir)
    }

    /** Jars for the catalog, for callers that only need the classpath. */
    fun resolvedJars(): List<File> = resolve().map { it.jar }
}
